function bookingsCount(count: number) {
  return plural("ar", count, {
    zero: "لا حجوزات",
    one: "حجز واحد",
    two: "حجزان",
    few: "{n} حجوزات",
    many: "{n} حجزًا",
    other: "{n} حجز",
  });
}

function daysCount(days: number) {
  return plural("ar", days, {
    one: "يوم واحد",
    two: "يومين",
    few: "{n} أيام",
    many: "{n} يومًا",
    other: "{n} يوم",
  });
}

